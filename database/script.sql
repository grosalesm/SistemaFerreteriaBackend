-- ---------------------------------------------------------------------
-- 2. db_auth  (ms-auth)
-- ---------------------------------------------------------------------
\connect db_auth

CREATE TABLE IF NOT EXISTS usuarios (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username        VARCHAR(50)  NOT NULL UNIQUE,
    email           VARCHAR(120) NOT NULL UNIQUE,
    password_hash   VARCHAR(255) NOT NULL,
    nombres         VARCHAR(100) NOT NULL,
    apellidos       VARCHAR(100) NOT NULL,
    rol             VARCHAR(20)  NOT NULL
                    CHECK (rol IN ('ADMIN', 'VENDEDOR', 'CAJERO', 'ALMACENERO')),
    activo          BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMP    NOT NULL DEFAULT now(),
    updated_at      TIMESTAMP    NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS refresh_tokens (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id      BIGINT       NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
    token           VARCHAR(255) NOT NULL UNIQUE,
    expira_en       TIMESTAMP    NOT NULL,
    revocado        BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMP    NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_refresh_tokens_usuario ON refresh_tokens (usuario_id);


-- ---------------------------------------------------------------------
-- 3. db_clientes  (ms-clientes)
-- ---------------------------------------------------------------------
\connect db_clientes

CREATE TABLE IF NOT EXISTS clientes (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_documento    VARCHAR(10)  NOT NULL CHECK (tipo_documento IN ('DNI', 'RUC', 'CE', 'PASAPORTE')),
    numero_documento  VARCHAR(20)  NOT NULL,
    razon_social      VARCHAR(200) NOT NULL,           -- nombre completo o razón social
    direccion         VARCHAR(250),
    telefono          VARCHAR(20),
    email             VARCHAR(120),
    activo            BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at        TIMESTAMP    NOT NULL DEFAULT now(),
    updated_at        TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT uk_clientes_documento UNIQUE (tipo_documento, numero_documento)
);
CREATE INDEX IF NOT EXISTS idx_clientes_razon_social ON clientes (razon_social);


-- ---------------------------------------------------------------------
-- 4. db_productos  (ms-productos)
-- ---------------------------------------------------------------------
\connect db_productos

CREATE TABLE IF NOT EXISTS categorias (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(100) NOT NULL UNIQUE,
    descripcion     VARCHAR(250),
    activo          BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMP    NOT NULL DEFAULT now(),
    updated_at      TIMESTAMP    NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS productos (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo          VARCHAR(30)    NOT NULL UNIQUE,
    nombre          VARCHAR(150)   NOT NULL,
    descripcion     VARCHAR(500),
    categoria_id    BIGINT         NOT NULL REFERENCES categorias (id),
    unidad_medida   VARCHAR(10)    NOT NULL,          -- UND, KG, M, BOLSA, GLN...
    precio_venta    NUMERIC(12, 2) NOT NULL CHECK (precio_venta >= 0),
    activo          BOOLEAN        NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMP      NOT NULL DEFAULT now(),
    updated_at      TIMESTAMP      NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_productos_categoria ON productos (categoria_id);
CREATE INDEX IF NOT EXISTS idx_productos_nombre    ON productos (nombre);

CREATE TABLE IF NOT EXISTS almacenes (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo          VARCHAR(20)  NOT NULL UNIQUE,
    nombre          VARCHAR(100) NOT NULL,
    direccion       VARCHAR(250),
    activo          BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMP    NOT NULL DEFAULT now(),
    updated_at      TIMESTAMP    NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS stock (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id       BIGINT         NOT NULL REFERENCES productos (id),
    almacen_id        BIGINT         NOT NULL REFERENCES almacenes (id),
    cantidad          NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (cantidad >= 0),
    cantidad_reservada NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (cantidad_reservada >= 0),
    stock_minimo      NUMERIC(12, 2) NOT NULL DEFAULT 0,
    version           BIGINT         NOT NULL DEFAULT 0,  -- bloqueo optimista (@Version)
    updated_at        TIMESTAMP      NOT NULL DEFAULT now(),
    CONSTRAINT uk_stock_producto_almacen UNIQUE (producto_id, almacen_id)
);

CREATE TABLE IF NOT EXISTS movimientos_stock (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id     BIGINT         NOT NULL REFERENCES productos (id),
    almacen_id      BIGINT         NOT NULL REFERENCES almacenes (id),
    tipo            VARCHAR(20)    NOT NULL
                    CHECK (tipo IN ('ENTRADA', 'SALIDA', 'AJUSTE', 'RESERVA', 'LIBERACION')),
    cantidad        NUMERIC(12, 2) NOT NULL CHECK (cantidad > 0),
    referencia      VARCHAR(50),                      -- p. ej. número de pedido
    usuario_id      BIGINT,
    observacion     VARCHAR(250),
    created_at      TIMESTAMP      NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_mov_stock_producto ON movimientos_stock (producto_id, created_at);


-- ---------------------------------------------------------------------
-- 5. db_cotizaciones  (ms-cotizaciones)
-- ---------------------------------------------------------------------
\connect db_cotizaciones

CREATE TABLE IF NOT EXISTS cotizaciones (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero             VARCHAR(20)    NOT NULL UNIQUE,   -- p. ej. COT-000123
    cliente_id         BIGINT         NOT NULL,
    usuario_id         BIGINT         NOT NULL,          -- vendedor
    fecha_emision      DATE           NOT NULL DEFAULT CURRENT_DATE,
    fecha_vencimiento  DATE           NOT NULL,
    estado             VARCHAR(20)    NOT NULL DEFAULT 'BORRADOR'
                       CHECK (estado IN ('BORRADOR', 'EMITIDA', 'APROBADA', 'RECHAZADA', 'VENCIDA', 'CONVERTIDA')),
    subtotal           NUMERIC(12, 2) NOT NULL DEFAULT 0,
    igv                NUMERIC(12, 2) NOT NULL DEFAULT 0,
    total              NUMERIC(12, 2) NOT NULL DEFAULT 0,
    observaciones      VARCHAR(500),
    created_at         TIMESTAMP      NOT NULL DEFAULT now(),
    updated_at         TIMESTAMP      NOT NULL DEFAULT now(),
    CONSTRAINT ck_cotizaciones_fechas CHECK (fecha_vencimiento >= fecha_emision)
);
CREATE INDEX IF NOT EXISTS idx_cotizaciones_cliente ON cotizaciones (cliente_id);
CREATE INDEX IF NOT EXISTS idx_cotizaciones_estado  ON cotizaciones (estado);

CREATE TABLE IF NOT EXISTS cotizacion_detalle (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cotizacion_id    BIGINT         NOT NULL REFERENCES cotizaciones (id) ON DELETE CASCADE,
    producto_id      BIGINT         NOT NULL,
    codigo_producto  VARCHAR(30)    NOT NULL,          -- copia al momento de cotizar
    descripcion      VARCHAR(150)   NOT NULL,
    unidad_medida    VARCHAR(10)    NOT NULL,
    cantidad         NUMERIC(12, 2) NOT NULL CHECK (cantidad > 0),
    precio_unitario  NUMERIC(12, 2) NOT NULL CHECK (precio_unitario >= 0),
    descuento        NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (descuento >= 0),
    subtotal         NUMERIC(12, 2) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_cot_detalle_cotizacion ON cotizacion_detalle (cotizacion_id);


-- ---------------------------------------------------------------------
-- 6. db_ventas  (ms-ventas)
-- ---------------------------------------------------------------------
\connect db_ventas

CREATE TABLE IF NOT EXISTS pedidos (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero           VARCHAR(20)    NOT NULL UNIQUE,    -- p. ej. PED-000045
    cotizacion_id    BIGINT,                             -- NULL si es venta directa
    cliente_id       BIGINT         NOT NULL,
    usuario_id       BIGINT         NOT NULL,           -- cajero / vendedor
    estado           VARCHAR(20)    NOT NULL DEFAULT 'REGISTRADO'
                     CHECK (estado IN ('REGISTRADO', 'PAGADO', 'EN_DESPACHO', 'ENTREGADO', 'ANULADO')),
    metodo_pago      VARCHAR(20)    NOT NULL
                     CHECK (metodo_pago IN ('EFECTIVO', 'TARJETA', 'YAPE', 'PLIN', 'TRANSFERENCIA')),
    subtotal         NUMERIC(12, 2) NOT NULL DEFAULT 0,
    igv              NUMERIC(12, 2) NOT NULL DEFAULT 0,
    total            NUMERIC(12, 2) NOT NULL DEFAULT 0,
    monto_recibido   NUMERIC(12, 2),
    vuelto           NUMERIC(12, 2),
    fecha_pago       TIMESTAMP,
    observaciones    VARCHAR(500),
    created_at       TIMESTAMP      NOT NULL DEFAULT now(),
    updated_at       TIMESTAMP      NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_pedidos_cliente    ON pedidos (cliente_id);
CREATE INDEX IF NOT EXISTS idx_pedidos_estado     ON pedidos (estado);
CREATE INDEX IF NOT EXISTS idx_pedidos_created_at ON pedidos (created_at);

CREATE TABLE IF NOT EXISTS pedido_detalle (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id        BIGINT         NOT NULL REFERENCES pedidos (id) ON DELETE CASCADE,
    producto_id      BIGINT         NOT NULL,
    codigo_producto  VARCHAR(30)    NOT NULL,
    descripcion      VARCHAR(150)   NOT NULL,
    unidad_medida    VARCHAR(10)    NOT NULL,
    cantidad         NUMERIC(12, 2) NOT NULL CHECK (cantidad > 0),
    precio_unitario  NUMERIC(12, 2) NOT NULL CHECK (precio_unitario >= 0),
    descuento        NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (descuento >= 0),
    subtotal         NUMERIC(12, 2) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_ped_detalle_pedido ON pedido_detalle (pedido_id);

CREATE TABLE IF NOT EXISTS despachos (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id          BIGINT       NOT NULL REFERENCES pedidos (id),
    almacen_id         BIGINT       NOT NULL,
    estado             VARCHAR(20)  NOT NULL DEFAULT 'PENDIENTE'
                       CHECK (estado IN ('PENDIENTE', 'EN_PREPARACION', 'DESPACHADO', 'ENTREGADO', 'CANCELADO')),
    tipo_entrega       VARCHAR(20)  NOT NULL DEFAULT 'RECOJO_TIENDA'
                       CHECK (tipo_entrega IN ('RECOJO_TIENDA', 'DELIVERY')),
    direccion_entrega  VARCHAR(250),
    fecha_programada   TIMESTAMP,
    fecha_despacho     TIMESTAMP,
    fecha_entrega      TIMESTAMP,
    usuario_id         BIGINT,                         -- almacenero responsable
    observaciones      VARCHAR(500),
    created_at         TIMESTAMP    NOT NULL DEFAULT now(),
    updated_at         TIMESTAMP    NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_despachos_pedido ON despachos (pedido_id);
CREATE INDEX IF NOT EXISTS idx_despachos_estado ON despachos (estado);


-- ---------------------------------------------------------------------
-- 7. db_notificaciones  (ms-notificaciones)
-- ---------------------------------------------------------------------
\connect db_notificaciones

CREATE TABLE IF NOT EXISTS notificaciones (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id      BIGINT,                            -- NULL = para todos / por rol
    rol_destino     VARCHAR(20),
    tipo            VARCHAR(30)  NOT NULL,             -- STOCK_BAJO, COTIZACION_APROBADA, PEDIDO_PAGADO...
    titulo          VARCHAR(150) NOT NULL,
    mensaje         VARCHAR(500) NOT NULL,
    referencia      VARCHAR(50),                       -- p. ej. PED-000045
    leida           BOOLEAN      NOT NULL DEFAULT FALSE,
    leida_en        TIMESTAMP,
    created_at      TIMESTAMP    NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_notificaciones_usuario ON notificaciones (usuario_id, leida);