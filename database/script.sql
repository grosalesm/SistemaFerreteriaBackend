--   psql -U postgres -f database/script.sql
--
-- Es idempotente: se puede volver a ejecutar sin errores.
-- Cada microservicio tiene su propia BD; las referencias entre servicios
-- (cliente_id, producto_id, usuario_id...) son IDs sin FK física.
